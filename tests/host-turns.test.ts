import { test, expect } from "bun:test";
import { Database } from "bun:sqlite";
import { HostTurns, turnEventStream } from "../src/server/host-turns";

const registration = { documentId: "doc-a", machineId: "machine-a", path: "/a.md", agentId: "paseo:agent-a", hostId: "host-a", owner: "local", behavior: "steer" as const };
test("host invitations survive service reconstruction, replay safely and require acceptance before completion", () => {
  const db = new Database(":memory:");
  let service = new HostTurns(db);
  service.register(registration);
  const press = service.request("doc-a", "paseo:agent-a", "operation-a");
  service = new HostTurns(db);
  expect(service.snapshot("local", "host-a").signals[0]!.state).toBe("pending");
  expect(service.request("doc-a", "paseo:agent-a", "operation-a").signalId).toBe(press.signalId);
  const lease = service.lease("local", "host-a", "instance");
  service.update("local", "host-a", lease.token, press.signalId, "claim", { position: { seq: 10, epoch: "session-a" } });
  expect(() => service.update("local", "host-a", lease.token, press.signalId, "claim")).toThrow("already claimed");
  service = new HostTurns(db);
  const next = service.lease("local", "host-a", "next-instance");
  expect(service.snapshot("local", "host-a").signals[0]!.state).toBe("dispatching");
  expect(() => service.update("local", "host-a", next.token, press.signalId, "completed")).toThrow("acceptance");
  service.update("local", "host-a", next.token, press.signalId, "uncertain");
  expect(() => service.request("doc-a", "paseo:agent-a", "second")).toThrow("review");
  service.update("local", "host-a", next.token, press.signalId, "accepted");
  service.update("local", "host-a", next.token, press.signalId, "completed");
  expect(service.agents("doc-a")[0]!.state).toBe("ready");
  expect(service.request("doc-a", "paseo:agent-a", "second").signalId).not.toBe(press.signalId);
  expect(() => service.update("local", "host-a", next.token, press.signalId, "completed")).toThrow("current");
  db.close();
});
test("host leases fence duplicate adapters, expired owners and different connections", () => {
  const db = new Database(":memory:"); let now = 1;
  const service = new HostTurns(db, () => now);
  service.register(registration);
  const press = service.request("doc-a", "paseo:agent-a", "op");
  const first = service.lease("local", "host-a", "first");
  expect(() => service.lease("local", "host-a", "second")).toThrow("Another");
  now += 46_000;
  const second = service.lease("local", "host-a", "second");
  expect(() => service.update("local", "host-a", first.token, press.signalId, "claim")).toThrow("expired");
  const other = service.lease("other", "host-a", "second");
  expect(() => service.update("other", "host-a", other.token, press.signalId, "claim")).toThrow("belong");
  service.revoke("local");
  expect(() => service.update("local", "host-a", second.token, press.signalId, "claim")).toThrow("expired");
  db.close();
});
test("document and host identity fence registration, operation replay and concurrent agent sends", () => {
  const db = new Database(":memory:"), service = new HostTurns(db);
  service.register(registration);
  expect(() => service.register({ ...registration, hostId: "other" })).toThrow("different");
  service.register({ ...registration, documentId: "doc-b", path: "/b.md" });
  const a = service.request("doc-a", "paseo:agent-a", "op-a");
  expect(() => service.request("doc-b", "paseo:agent-a", "op-a")).toThrow("different");
  const b = service.request("doc-b", "paseo:agent-a", "op-b");
  const lease = service.lease("local", "host-a", "worker");
  service.update("local", "host-a", lease.token, a.signalId, "claim");
  expect(() => service.update("local", "host-a", lease.token, b.signalId, "claim")).toThrow("active delivery");
  expect(service.snapshot("other", "host-a").signals).toEqual([]);
  db.close();
});

test("revoking a stream closes it and removing a claimed subscription blocks its final send check", async () => {
  const db = new Database(":memory:"), service = new HostTurns(db), lifetime = new AbortController();
  service.register(registration);
  let live = true;
  const stream = turnEventStream(lifetime.signal, fn => service.subscribe(fn), () => service.snapshot("local", "host-a"), () => live);
  const reader = stream.body!.getReader();
  expect(new TextDecoder().decode((await reader.read()).value)).toContain('"subscriptions"');
  const signal = service.request("doc-a", "paseo:agent-a", "stream-press");
  await reader.read();
  const lease = service.lease("local", "host-a", "adapter");
  service.update("local", "host-a", lease.token, signal.signalId, "claim");
  await reader.read();
  live = false;
  service.unregister("doc-a", "paseo:agent-a");
  expect((await reader.read()).done).toBe(true);
  expect(() => service.verify("local", "host-a", lease.token, signal.signalId)).toThrow("dispatchable");
  lifetime.abort(); db.close();
});
